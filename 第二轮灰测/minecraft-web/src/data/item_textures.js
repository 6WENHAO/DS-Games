/** 用配色渲染一张 ASCII 图案 */
export function paintArt(t, art, colors) {
  t.clear();
  const map = {
    M: colors.M, m: colors.m ?? shade(colors.M, 0.72), L: colors.L ?? shade(colors.M, 1.25),
    H: colors.H ?? HANDLE, h: colors.h ?? HANDLE_D, G: colors.G ?? GUARD,
    x: '#1a1a1a',
  };
  for (let y = 0; y < art.length && y < 16; y++) {
    const row = art[y];
    for (let x = 0; x < row.length && x < 16; x++) {
      const ch = row[x];
      if (ch === '.' || ch === ' ') continue;
      const c = map[ch];
      if (c) t.set(x, y, c);
    }
  }
  return t;
}

